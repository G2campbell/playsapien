/* Regenerates src/lib/wordlist.js from Word Chain's dictionary.

     node scripts/make-wordlist.mjs

   The Worker cannot read games/wordchain/src/dict.txt at run time, so the list
   is copied in as a module -- the same filter Word Chain's build applies (2 to
   18 letters, upper case). test/wordlist.test.js fails if the copy has drifted
   from dict.txt, so a dictionary change cannot ship half-done. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export function wordsFromDict(text) {
  return [...new Set(text.split(/\r?\n/).map((w) => w.trim())
    .filter((w) => w.length >= 2 && w.length <= 18).map((w) => w.toUpperCase()))].sort();
}
export const DICT_PATH = join(here, '..', '..', 'games', 'wordchain', 'src', 'dict.txt');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const words = wordsFromDict(readFileSync(DICT_PATH, 'utf8'));
  const out = '/* GENERATED by scripts/make-wordlist.mjs from games/wordchain/src/dict.txt.\n' +
    '   Do not edit by hand. ' + words.length + ' words. */\n' +
    'export default ' + JSON.stringify(words.join('\n')) + ';\n';
  writeFileSync(join(here, '..', 'src', 'lib', 'wordlist.js'), out);
  console.log('wordlist.js:', words.length, 'words');
}
